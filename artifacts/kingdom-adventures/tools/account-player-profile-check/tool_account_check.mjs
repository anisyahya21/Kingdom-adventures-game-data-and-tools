import assert from "node:assert/strict";
import { gameAccountContext, selectedGameAccount, selectGameAccount, gameAccountScope } from "../../src/lib/game-accounts.ts";
import { accountEquipmentRows, levelingStorageKey, withCurrentEquipmentLevel } from "../../src/lib/equipment-leveling-account.ts";
const data = new Map();
globalThis.localStorage = { getItem: (key) => data.get(key) || null, setItem: (key, value) => data.set(key, value) };
globalThis.window = { location: { pathname: "/combat" }, dispatchEvent: () => {} };
globalThis.CustomEvent = class { constructor(type) { this.type = type; } };
const accounts = [{ id: "primary" }, { id: "second" }, { id: "third" }];
selectGameAccount("user", "second");
assert.equal(selectedGameAccount("user", accounts), "second");
window.location.pathname = "/equipment-leveling-optimizer";
assert.equal(selectedGameAccount("user", accounts), "primary");
selectGameAccount("user", "third");
assert.equal(selectedGameAccount("user", accounts), "third");
window.location.pathname = "/combat/multi-box";
assert.equal(selectedGameAccount("user", accounts), "second");
window.location.pathname = "/player-profile";
assert.equal(selectedGameAccount("user", accounts), "primary");
selectGameAccount("user", "third");
window.location.pathname = "/combat/character-builder";
assert.equal(selectedGameAccount("user", accounts), "second");
assert.equal(selectedGameAccount("other-user", accounts), "primary");
assert.equal(selectedGameAccount("user", [{ id: "primary" }]), "primary");
assert.equal(gameAccountContext("/equipment-level-optimizer"), "leveling");
assert.equal(gameAccountContext("/loadout"), "combat");
assert.equal(gameAccountContext("/houses"), "profile");
const main = gameAccountScope("user", "primary");
const second = gameAccountScope("user", "second");
assert.notEqual(levelingStorageKey("planner", main), levelingStorageKey("planner", second));
assert.equal(levelingStorageKey("planner", null), "planner");
const equipment = { Staff: 37, Shield: 12 };
const snapshot = JSON.stringify(equipment);
assert.deepEqual(accountEquipmentRows([{ id: 1, name: "Staff" }, { id: 2, name: "Shield" }, { id: 3, name: "Sword" }], equipment), {
  1: { checked: true, level: 37 }, 2: { checked: true, level: 12 }, 3: { checked: false, level: 1 },
});
assert.equal(JSON.stringify(equipment), snapshot, "Planning import must not change recorded levels");
const profile = { equipment: { Staff: 37, Shield: 12 }, characters: [{ id: "keep" }], valuables: { water: 4 } };
const updated = withCurrentEquipmentLevel(profile, "Staff", 52);
assert.equal(updated.equipment.Staff, 52);
assert.equal(updated.equipment.Shield, 12);
assert.equal(profile.equipment.Staff, 37);
assert.equal(updated.characters, profile.characters);
assert.equal(updated.valuables, profile.valuables);
assert.equal(withCurrentEquipmentLevel(updated, "Staff", 52), updated);
assert.equal(withCurrentEquipmentLevel(updated, "Staff", Number.NaN), updated);
assert.equal(withCurrentEquipmentLevel(updated, "Staff", 1000).equipment.Staff, 99);
assert.equal(withCurrentEquipmentLevel(updated, "Staff", 0).equipment.Staff, 1);
const planning = { target: 88, checked: false };
withCurrentEquipmentLevel(profile, "Staff", 62);
assert.deepEqual(planning, { target: 88, checked: false });
console.log(JSON.stringify({ ok: true, checks: 25, coverage: "independent tool choices, user isolation, per-account plans, shared current-level edits, preserved other profile data" }));
