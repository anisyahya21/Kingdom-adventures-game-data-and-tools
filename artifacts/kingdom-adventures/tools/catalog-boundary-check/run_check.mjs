import assert from 'node:assert/strict';
import fs from 'node:fs';
import { measuredPointFor, bestMeasuredPanel } from '../../src/lib/chest-strategy-boundary-access.ts';
import { register } from 'node:module';
register('../battle-setup-check/ts-loader.mjs', import.meta.url);
const { CHEST_STRATEGY_OPTIONS, strategyOptionForProfileBuild, chestStrategyGoals } = await import('../../src/lib/chest-strategy-targets.ts');
const data = JSON.parse(fs.readFileSync(new URL('../../src/game-data/chest-strategy-targets.json',import.meta.url)));
const boundaries = JSON.parse(fs.readFileSync(new URL('../../src/game-data/chest-strategy-boundaries.json',import.meta.url)));
const options = CHEST_STRATEGY_OPTIONS;
assert.equal(options.length,73);
assert.equal(new Set(options.map(o=>o.id)).size,options.length);
assert.equal(new Set(options.map(o=>[o.encounter,o.atk,o.spd,o.lck,o.dex].join('/'))).size,options.length);
assert.equal(new Set(options.map(o=>o.encounter)).size,20);
assert.equal(data.fixedSetup.mpPerRole,10000000);
assert.equal(boundaries.panels.length,options.length);
for (const o of options) {
  assert.equal(o.n,200);
  assert.equal(o.mpMode,'sufficient');
  for(const k of ['mean','highest','median','meanDpsMp','meanHealerMp']) assert.ok(Number.isFinite(o[k]),`${o.id}: ${k}`);
  assert.ok(o.lck>0 && o.dex>0);
  assert.ok(!(o.encounter===19 && o.atk===333 && o.spd===220 && o.lck===110));
  assert.ok(o.lowAtMost1>=0 && o.lowAtMost1<=o.n && o.defeats>=0 && o.defeats<=o.n);
  assert.equal(o.seedRange[1]-o.seedRange[0]+1,o.n);
  const p=measuredPointFor(boundaries,o.encounter,[o.atk,o.spd,o.lck,o.dex]);
  assert.ok(p); assert.equal(p.mean,o.mean); assert.equal(p.setupId,o.setupId); assert.equal(p.sourceCohort,o.sourceCohort);
  assert.deepEqual(p.variants,[],'Old MP-limited deviation evidence must not be transferred');
  assert.equal(measuredPointFor(boundaries,o.encounter,[o.atk,o.spd,o.lck,o.dex+123456]),null);
  const goals=chestStrategyGoals(o,{atk:0,spd:0,lck:0});
  assert.equal(goals.dex.min,o.dex); assert.equal(goals.dex.max,o.dex);
  const unknown=strategyOptionForProfileBuild(o,{atk:o.atk+1,spd:o.spd,lck:o.lck,dex:o.dex},null);
  for(const k of ['mean','highest','n','median','meanDpsMp','meanHealerMp','setupId']) assert.equal(unknown[k],undefined);
}
assert.equal(bestMeasuredPanel([{n:200,mean:99,seedRange:[1,200]},{n:200,mean:1,seedRange:[201,400]}]).mean,1);
console.log(`PASS: ${options.length} sufficient-MP exact options, all 20 encounters, no inherited boundaries or unmeasured reward claims.`);
