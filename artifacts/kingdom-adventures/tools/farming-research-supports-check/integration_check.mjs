import assert from 'node:assert/strict';
import fs from 'node:fs';
import { battleSetupFromLoadouts } from '../../src/lib/battle-legality.ts';
import { battleSetupToCombatScenario } from '../../src/lib/battle-setup-adapter.ts';
import { draftCharacterFromLoadout, normalizeDraft, BATTLE_TEAM_DRAFT_SCHEMA } from '../../src/lib/battle-team-draft.ts';
import { farmingDpsSkills, writeFarmingSimulationHandoff, readFarmingSimulationHandoff } from '../../src/lib/farming-planner.ts';
import { farmingResearchSupportLoadouts, applyFarmingResearchSupports } from '../../src/lib/farming-research-supports.ts';
import { validateBattleSetup } from '../../src/lib/battle-setup.ts';
const shared=JSON.parse(fs.readFileSync(new URL('../../../api-server/data/ka_shared.json',import.meta.url),'utf8'));
const dps={name:'Profile DPS',jobName:'Ninja',rank:'A',gender:0,statLevels:{hp:321,mp:337,vig:254,atk:5,def:176,spd:3,lck:1,int:3,dex:1,gth:4,mov:1,hrt:1},equipment:[{name:'B/ Mystic Hat',level:99},{name:'F/ Wooden Stick',level:99},{name:'B/ Legendary Shield (B)',level:60},{name:'C/ Light Mail',level:1},{name:'E/ Leather Shoes',level:5}],skills:farmingDpsSkills(['Shield Resistance']),residentStatItems:{}};
dps.skillInvocations=dps.skills.map(()=>0);
assert.equal(dps.skills.length,7); assert.equal(dps.skills.at(-1),'Shield Resistance');
const conversion=battleSetupFromLoadouts([dps,...farmingResearchSupportLoadouts()],shared,{encounterId:3,partyMax:6,holyHerbStock:10});
assert.deepEqual(conversion.issues.filter(x=>x.category==='ERROR'),[]);
assert.ok(conversion.setup);
const synthetic=applyFarmingResearchSupports(conversion.setup);
assert.equal(synthetic.playerTeam[0],conversion.setup.playerTeam[0]);
assert.equal(synthetic.holyHerbStock,10);
assert.deepEqual(synthetic.playerTeam[0].skills.map(s=>s.skillId),[26,110,25,24,23,22,91]);
assert.deepEqual(validateBattleSetup(synthetic).filter(x=>x.category==='ERROR'),[]);
const scenario=battleSetupToCombatScenario(synthetic).scenario;
assert.equal(scenario.ownUnits.length,6);
assert.equal(scenario.ownUnits[1].parameters['11'].rawValue,10000000);
assert.notEqual(scenario.ownUnits[0].parameters['11'].rawValue,10000000);
assert.deepEqual(scenario.ownUnits[1].skills,[37,107]);
assert.deepEqual(scenario.ownUnits[0].invocationLevels,[0,0,0,0,0,0,0]);
assert.deepEqual(scenario.ownUnits.slice(2).map(u=>u.skills),[[],[],[],[]]);
const draft={schema:BATTLE_TEAM_DRAFT_SCHEMA,encounterId:3,characters:[dps,...farmingResearchSupportLoadouts()].map((x,i)=>draftCharacterFromLoadout(x,i+1)),researchSupports:'fixed-spd4456-v1',partyBonus:4};
assert.equal(normalizeDraft(draft).researchSupports,'fixed-spd4456-v1');
const memory=new Map(); globalThis.window={sessionStorage:{getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)}};
assert.equal(writeFarmingSimulationHandoff({loadout:dps,encounterId:3,placeholderSupports:true,allowConsumables:true,startingTeamId:'',consumables:{holyHerbStock:10,itemStock:{}}}),true);
assert.equal(readFarmingSimulationHandoff().loadout.skills.at(-1),'Shield Resistance'); assert.equal(readFarmingSimulationHandoff(),null);
console.log('PASS: six-role farming setup converts, validates and adapts; finite DPS MP and required mastery preserved; support mode survives storage; handoff consumed once.');

