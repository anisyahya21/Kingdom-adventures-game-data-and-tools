import assert from "node:assert/strict";
import { measuredStrategyBoundaries, measuredStrategyBuild } from "../../src/lib/chest-strategy-boundaries.ts";
const cohorts = measuredStrategyBoundaries("e19-atk238-spd389-lck336");
const anchor = cohorts.at(-1);
assert.equal(anchor.n,120);
assert.deepEqual(anchor.seedRange,[2386,2505]);
const earlier = cohorts.find(panel => panel.seedRange[0] === 2266);
assert.ok(earlier.mean > 34 && earlier.mean < 36,"preserve the earlier cohort's measured mean");
assert.equal(measuredStrategyBuild(19,{atk:238,spd:389,lck:336,dex:18}).mean,anchor.mean);
assert.equal(measuredStrategyBuild(19,{atk:238,spd:389,lck:336,dex:49}).stats[3],49);
assert.equal(measuredStrategyBuild(19,{atk:238,spd:390,lck:336,dex:18}),null,"untested adjacent point cannot inherit average");
assert.equal(measuredStrategyBuild(7,{atk:238,spd:389,lck:336,dex:18}),null,"encounters cannot share reward evidence");
assert.equal(measuredStrategyBoundaries("e0-atk67-spd88-lck34").length,1,"newly covered target has its fresh panel");
assert.ok(cohorts.length >= 2,"retain separate old and new validation cohorts");
const slower = measuredStrategyBuild(19,{atk:238,spd:379,lck:336,dex:18});
assert.equal(slower.mean,cohorts.find(panel => panel.seedRange[0] === slower.seedRange[0]).mean,"compare equality within the matching cohort");
const oldE3 = measuredStrategyBoundaries("e3-atk994-spd656-lck126").find(panel => panel.seedRange[0] === 2266);
assert.ok(oldE3.variants.find(point => point.stats[0] === 894).low > oldE3.low,"similar averages must retain distinct same-cohort low-reward evidence");
console.log("PASS exact four-stat evidence: DEX, encounter and unknown adjacent tuples stay distinct.");
